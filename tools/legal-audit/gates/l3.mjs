// L3 - Secret scan (Workflow.md 4.2, R-SEC-2).
//
// Runs gitleaks (https://github.com/gitleaks/gitleaks) in one or more modes (`--mode`, repeatable; default `tree`):
//   tree     `gitleaks dir <root>`                           the working tree (equivalent to the older `detect --no-git`)
//   diff     `gitleaks git --log-opts <base>..<head> <root>`  only the commits of a pull request (needs --base, --head)
//   history  `gitleaks git <root>`                            the complete history (nightly)
// Any finding is an error. Waivers (gate L3) match `finding.subject` = the gitleaks fingerprint
// (`[commit:]path:rule:line`), which never contains the secret.
//
// Secrets never leave this process: gitleaks runs with `--redact` (100 %), its raw report lives in a temp dir that is
// removed afterwards, only a whitelist of fields (rule, file, line, commit, fingerprint, entropy) is copied into the
// evidence, author name / e-mail / commit message are dropped (personal data, may quote the secret), and every string
// written to outDir or returned is scrubbed against any secret values still present in the raw report.
//
// Build output that is never committed is excluded from `tree` scans: node_modules, target, .next, .dev and the gate's
// own outDir when it lies inside the root. A generated config extends the repository's `.gitleaks.toml` (or the gitleaks
// default rules) with that allowlist, so the repository config stays authoritative for rules.
//
// Options: --gitleaks <bin> --mode <tree|diff|history> --base <rev> --head <rev> --config <toml> --git <bin>
//          --skip-reason <text>        Env: LEGAL_AUDIT_GITLEAKS
// Evidence: gitleaks-report.json
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, relative, resolve } from 'node:path';
import { describeFailure, resolveBinary, run as runProcess, toolVersion } from '../lib/exec.mjs';
import { applyWaivers, hashInputs, loadWaivers, missingTool, optList, optString, sha256File, skipRequested } from '../lib/common.mjs';
import { isGitRepo, isZeroSha, revParse } from '../lib/git.mjs';
import { error, info, result, statusFromFindings, writeJson } from '../lib/result.mjs';

export const id = 'L3';
export const name = 'Secret scan';

const MODES = ['tree', 'diff', 'history'];
const LEAKS_EXIT = 42; // chosen so that gitleaks' own failure exit code (1) is not confused with "leaks found"
const EXCLUDED_DIRS = ['node_modules', 'target', '.next', '.dev'];

const escapeRegex = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** TOML for the generated gitleaks config (see header). */
export function buildConfigToml({ userConfig, outDirRel }) {
  const dirs = EXCLUDED_DIRS.map(escapeRegex);
  const paths = [`(^|[\\\\/])(${dirs.join('|')})([\\\\/]|$)`];
  if (outDirRel) paths.push(`^${escapeRegex(outDirRel)}([\\\\/]|$)`);
  const extend = userConfig ? `path = '''${userConfig.replaceAll('\\', '/')}'''` : 'useDefault = true';
  return [
    '# generated by legal-audit L3: extends the repository gitleaks config and excludes untracked build output',
    '[extend]',
    extend,
    '',
    '[[allowlists]]',
    'description = "legal-audit L3: build output that is never committed"',
    `paths = [${paths.map((p) => `'''${p}'''`).join(', ')}]`,
    '',
  ].join('\n');
}

/**
 * Whitelisted, secret-free view of one raw gitleaks finding. Exported for tests against real gitleaks output.
 * @param {object} raw   one entry of the gitleaks JSON report
 * @param {string} [root] repository root; absolute paths below it (tree scans) are reported relative to it
 */
export function safeFinding(raw, root) {
  const prefix = root ? `${root.replaceAll('\\', '/').replace(/\/$/, '')}/` : null;
  const norm = (s) => {
    const t = String(s).replaceAll('\\', '/');
    return prefix && t.startsWith(prefix) ? t.slice(prefix.length) : t;
  };
  return {
    rule: raw.RuleID,
    description: raw.Description,
    file: norm(raw.File ?? ''),
    line: raw.StartLine,
    commit: raw.Commit ? String(raw.Commit) : null,
    fingerprint: norm(raw.Fingerprint ?? `${raw.File}:${raw.RuleID}:${raw.StartLine}`),
    entropy: raw.Entropy,
    tags: raw.Tags ?? [],
  };
}

/** Secret values that a (mis-)configured gitleaks left in a raw finding; used to scrub every outgoing string. */
export function leftoverSecrets(raws) {
  const out = new Set();
  for (const r of raws) {
    for (const v of [r.Secret, r.Match]) {
      if (typeof v === 'string' && v.length >= 4 && !/^REDACTED$/i.test(v) && !/^[*.\sX]+$/.test(v)) out.add(v);
    }
  }
  return [...out];
}

export function scrubber(secrets) {
  const sorted = [...secrets].sort((a, b) => b.length - a.length);
  return (text) => sorted.reduce((t, s) => t.split(s).join('[REDACTED]'), text);
}

function describeFinding(f, mode) {
  const where = `${f.file}${f.line ? `:${f.line}` : ''}`;
  const commit = f.commit ? ` in commit ${f.commit.slice(0, 12)}` : '';
  return `${f.rule}${f.description ? ` (${f.description})` : ''} at ${where}${commit} [${mode} scan; secret redacted]`;
}

export async function run(ctx) {
  const skipped = skipRequested(id, name, ctx);
  if (skipped) return skipped;

  const findings = [];
  const tools = {};
  const modes = optList(ctx, 'mode');
  if (modes.length === 0) modes.push('tree');
  const badMode = modes.find((m) => !MODES.includes(m));
  if (badMode) {
    return result(id, 'fail', { summary: `unknown --mode ${badMode}`, findings: [error(`unknown --mode "${badMode}" (expected ${MODES.join(', ')})`)] });
  }
  const uniqueModes = [...new Set(modes)];

  const bin = resolveBinary('gitleaks', { explicit: ctx.opts.gitleaks, envVar: 'LEGAL_AUDIT_GITLEAKS' });
  if (!bin) {
    const f = missingTool('gitleaks', 'install it from https://github.com/gitleaks/gitleaks/releases or pass --gitleaks <path> (LEGAL_AUDIT_GITLEAKS)');
    return result(id, 'fail', { summary: 'gitleaks is not available; secrets were NOT scanned', findings: [f] });
  }
  tools.gitleaks = (await toolVersion(bin, ['version'])) ?? 'unknown';

  const cfgOpt = optString(ctx, 'config');
  const userConfigPath = cfgOpt ? resolve(ctx.root, cfgOpt) : existsSync(join(ctx.root, '.gitleaks.toml')) ? join(ctx.root, '.gitleaks.toml') : null;
  if (cfgOpt && !existsSync(userConfigPath)) {
    return result(id, 'fail', { summary: `gitleaks config ${cfgOpt} not found`, findings: [error(`--config ${cfgOpt} does not exist`, cfgOpt)] });
  }

  const tmp = mkdtempSync(join(tmpdir(), 'legal-audit-gitleaks-'));
  const modeReports = [];
  const safe = new Map(); // fingerprint -> finding (+ modes)
  let allSecrets = [];
  try {
    const outRel = relative(ctx.root, ctx.outDir).replaceAll('\\', '/');
    const outDirRel = outRel && !outRel.startsWith('..') && !/^[A-Za-z]:/.test(outRel) ? outRel : null;
    const cfgPath = join(tmp, 'gitleaks.toml');
    writeFileSync(cfgPath, buildConfigToml({ userConfig: userConfigPath, outDirRel }));

    for (const mode of uniqueModes) {
      const reportPath = join(tmp, `report-${mode}.json`);
      const common = ['--config', cfgPath, '--report-format', 'json', '--report-path', reportPath, '--redact=100', '--no-banner', '--no-color', '--log-level', 'error', '--exit-code', String(LEAKS_EXIT), '--gitleaks-ignore-path', ctx.root];
      let args;
      let base = null;
      let head = null;
      if (mode === 'tree') args = ['dir', ...common, ctx.root];
      else {
        if (!(await isGitRepo(ctx.root, ctx.opts))) {
          findings.push(error(`${mode} scan needs a git repository but ${ctx.root} is not one`, mode));
          modeReports.push({ mode, status: 'not-run' });
          continue;
        }
        if (mode === 'history') args = ['git', ...common, ctx.root];
        else {
          const b = optString(ctx, 'base');
          const h = optString(ctx, 'head');
          if (!b || !h) {
            findings.push(error('diff scan needs --base <rev> and --head <rev>', 'diff'));
            modeReports.push({ mode, status: 'not-run' });
            continue;
          }
          if (isZeroSha(b)) {
            findings.push(error(`diff scan: --base ${b} is the all-zero SHA (no previous commit); run --mode history instead`, 'diff'));
            modeReports.push({ mode, status: 'not-run' });
            continue;
          }
          try {
            base = await revParse(ctx.root, b, ctx.opts);
            head = await revParse(ctx.root, h, ctx.opts);
          } catch (e) {
            findings.push(error(`diff scan: cannot resolve revisions: ${e.message}`, 'diff'));
            modeReports.push({ mode, status: 'not-run' });
            continue;
          }
          args = ['git', ...common, '--log-opts', `${base}..${head}`, ctx.root];
        }
      }

      const r = await runProcess(bin, args, { cwd: ctx.root, timeoutMs: 1_800_000 });
      let raws = [];
      let reportOk = true;
      if (existsSync(reportPath)) {
        try {
          const parsed = JSON.parse(readFileSync(reportPath, 'utf8') || '[]');
          raws = Array.isArray(parsed) ? parsed : [];
        } catch {
          reportOk = false;
        }
      } else if (r.code === LEAKS_EXIT) reportOk = false;
      allSecrets = allSecrets.concat(leftoverSecrets(raws));
      const scrub = scrubber(allSecrets);

      if (r.code !== 0 && r.code !== LEAKS_EXIT) {
        findings.push(error(`gitleaks ${mode} scan failed: ${scrub(describeFailure(r))}`, mode));
        modeReports.push({ mode, status: 'error', exit_code: r.code });
        continue;
      }
      if (!reportOk || (r.code === LEAKS_EXIT && raws.length === 0)) {
        findings.push(error(`gitleaks ${mode} scan reported leaks but its report is missing or unreadable`, mode));
        modeReports.push({ mode, status: 'error', exit_code: r.code });
        continue;
      }
      for (const raw of raws) {
        const f = safeFinding(raw, ctx.root);
        const key = f.fingerprint;
        if (safe.has(key)) safe.get(key).modes.push(mode);
        else safe.set(key, { ...f, modes: [mode] });
      }
      modeReports.push({ mode, status: raws.length > 0 ? 'findings' : 'clean', exit_code: r.code, findings: raws.length, ...(base ? { base, head } : {}), command: scrub(r.command) });
    }
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }

  const scrub = scrubber(allSecrets);
  const entries = [...safe.values()].sort((a, b) => a.fingerprint.localeCompare(b.fingerprint));
  for (const f of entries) findings.push(error(scrub(describeFinding(f, f.modes.join('+'))), scrub(f.fingerprint)));
  if (entries.length === 0 && !findings.some((f) => f.severity === 'error')) {
    findings.push(info(`no secrets found (modes: ${uniqueModes.join(', ')})`));
  }

  const report = JSON.parse(scrub(JSON.stringify({
    generated_at: ctx.now.toISOString(),
    modes: modeReports,
    excluded_dirs: EXCLUDED_DIRS,
    config: userConfigPath ? relative(ctx.root, userConfigPath).replaceAll('\\', '/') : 'gitleaks default rules',
    findings: entries,
  })));
  const evidence = [writeJson(ctx.outDir, 'gitleaks-report.json', report)];

  const wv = loadWaivers(ctx.root, id, ctx.now);
  const applied = applyWaivers(findings, wv.waivers);
  const all = [...applied.findings, ...wv.findings];
  return result(id, statusFromFindings(all), {
    summary: `${entries.length} potential secret(s) in ${uniqueModes.join('+')} scan`,
    findings: all,
    evidence,
    metrics: { findings: entries.length, modes: uniqueModes.length },
    inputs: {
      ...hashInputs(ctx.root, ['docs/waivers.yml', '.gitleaksignore']),
      ...(userConfigPath && sha256File(userConfigPath) ? { [relative(ctx.root, userConfigPath).replaceAll('\\', '/')]: sha256File(userConfigPath) } : {}),
    },
    tools,
    waived: applied.waived,
  });
}
